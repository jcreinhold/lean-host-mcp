//! One native compatibility contract, distinct from loaded execution evidence.
//!
//! `ExpectedContract` is safe on a cold status path: it says what the broker
//! requires, not what any child has loaded. `LoadedReceipt` can only be made
//! after a child host session reports its manifest-checked bindings. Package
//! versions are recorded rather than pinned. Only the shared-writer executable identity is observed here; no backend work is submitted.

use std::collections::BTreeMap;
use std::path::PathBuf;

use lean_rs_worker_parent::{
    LeanWorkerHostRuntimeExpectation, LeanWorkerHostRuntimeMetadata, LeanWorkerRuntimeMetadata,
};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

pub(crate) const SCHEMA: &str = "lean-host-native-compatibility-v1";

/// Actual helper location and required semantic interface, not a binary pin.
#[derive(Clone, Debug, Serialize, JsonSchema)]
pub struct SharedWriterObservation {
    pub protocol: u32,
    pub executable: PathBuf,
    /// Namespace bound to this broker's native generation ownership.
    pub ownership_registry: PathBuf,
}

impl From<lean_rs_writer::WriterContract> for SharedWriterObservation {
    fn from(writer: lean_rs_writer::WriterContract) -> Self {
        Self {
            protocol: writer.protocol,
            executable: writer.executable,
            ownership_registry: writer.ownership_registry,
        }
    }
}

/// Successful `lean_compatibility` evidence, including an actual loaded worker.
#[derive(Clone, Debug, Serialize, JsonSchema)]
pub struct CompatibilityEvidence {
    pub server_instance_id: String,
    pub contract_sha256: String,
    pub expected: ExpectedContract,
    pub loaded: Vec<LoadedReceipt>,
    pub shared_writer: SharedWriterObservation,
}

impl CompatibilityEvidence {
    /// Bind nonempty loaded receipts and the current helper observation.
    ///
    /// # Errors
    /// Refuses absent or mismatched receipts and an incompatible helper protocol.
    pub fn new(
        server_instance_id: String,
        expected: ExpectedContract,
        loaded: Vec<LoadedReceipt>,
    ) -> Result<Self, String> {
        let contract_sha256 = expected.digest().map_err(|error| error.to_string())?;
        if loaded.is_empty()
            || loaded.iter().any(|receipt| {
                receipt.server_instance_id != server_instance_id || receipt.contract_sha256 != contract_sha256
            })
        {
            return Err("actual compatible worker receipts from this broker are required".into());
        }
        let writer = lean_rs_writer::contract().map_err(|error| error.to_string())?;
        if writer.protocol != expected.writer_protocol {
            return Err("shared writer helper protocol is incompatible".into());
        }
        let shared_writer = SharedWriterObservation::from(writer);
        Ok(Self {
            server_instance_id,
            contract_sha256,
            expected,
            loaded,
            shared_writer,
        })
    }
}

/// Requirements owned by the broker's semantic API and host dependency.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, JsonSchema)]
pub struct ExpectedContract {
    pub schema: String,
    pub native_api: String,
    /// Existing negotiated extensions, including their lifecycle guarantees.
    pub capabilities: Vec<String>,
    /// Opaque ABI identifiers computed by lean-rs from required checked
    /// binding signatures. These are interface fingerprints, not file hashes.
    pub required_host_bindings: BTreeMap<String, String>,
    pub enforcement: String,
    pub writer_protocol: u32,
}

impl ExpectedContract {
    /// Build a structural expected contract from independently supplied ABI requirements.
    /// Production callers use [`Self::compiled`], never an actual worker report.
    ///
    /// # Errors
    /// Refuses missing operations or malformed interface fingerprints.
    pub fn new(required_host_bindings: BTreeMap<String, String>) -> Result<Self, String> {
        if required_host_bindings.is_empty()
            || required_host_bindings
                .iter()
                .any(|(name, abi)| name.trim().is_empty() || !is_digest(abi))
        {
            return Err("supported host binding contract is unavailable".into());
        }
        Ok(Self {
            schema: SCHEMA.into(),
            native_api: "shared-native-checks-v1".into(),
            capabilities: vec![
                "durable_requests_v1".into(),
                "generation_bound_worker_stop_v1".into(),
                "capacity_until_reaped_v1".into(),
                "worker_owned_shared_artifact_reads_v1".into(),
                "native_reader_stdout_frame_v1".into(),
            ],
            required_host_bindings,
            enforcement: "every-host-session-before-body-commands".into(),
            writer_protocol: lean_rs_writer::PROTOCOL,
        })
    }

    /// Requirements generated by the same link-free typed rows as host bindings.
    ///
    /// This does not initialize Lean, load a library or inspect a worker.
    ///
    /// # Errors
    /// Refuses missing or malformed SDK binding identities.
    pub fn compiled() -> Result<Self, String> {
        Self::new(lean_toolchain::host_shim_abi::expected_checked_bindings())
    }

    /// Instance and package identities intentionally do not affect compatibility.
    ///
    /// # Errors
    /// Returns the canonical tuple serialization error.
    pub fn digest(&self) -> Result<String, serde_json::Error> {
        // Fixed field order and BTreeMap order form the one cross-language
        // digest encoding; incoming JSON object order never affects it.
        let bytes = serde_json::to_vec(&(
            &self.schema,
            &self.native_api,
            &self.capabilities,
            &self.required_host_bindings,
            &self.enforcement,
            self.writer_protocol,
        ))?;
        Ok(crate::digest::sha256_hex(&bytes))
    }
}

/// Read epoch observed from an actual worker-held shared lock during this session.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct ArtifactReadEpoch {
    pub project_root: String,
    pub epoch: String,
}

/// Actual facts emitted by the worker child after checked host-session opening.
/// No constructor fills these from status, configured paths, or worker.json.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct LoadedHostRuntime {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub artifact_read_epochs: Option<Vec<ArtifactReadEpoch>>,
    /// Compile identity of the running child, not a runtime C-ABI version query.
    pub compiled_lean_version: String,
    pub compiled_header_sha256: String,
    /// Read through the actually loaded optional Lean runtime-version shim.
    pub runtime_lean_version: Option<String>,
    /// Each entry exists only after that typed binding was successfully resolved
    /// against the loaded capability's captured manifest and loaded symbol.
    pub checked_host_bindings: BTreeMap<String, String>,
}

/// The server's actor/generation binding for actual child-supplied facts.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, JsonSchema)]
pub struct LoadedReceipt {
    pub schema: String,
    pub contract_sha256: String,
    pub server_instance_id: String,
    pub project_root: String,
    pub lean_toolchain: String,
    pub worker_session_id: String,
    pub worker_generation: u64,
    pub worker_version: String,
    pub protocol_version: u16,
    pub loaded: LoadedHostRuntime,
}

#[derive(Clone, Copy)]
pub(crate) struct WorkerBinding<'a> {
    pub server_instance_id: &'a str,
    pub project_root: &'a str,
    pub lean_toolchain: &'a str,
    pub expected_header_sha256: &'a str,
    pub expected_runtime_lean_version: &'a str,
    pub worker_session_id: &'a str,
    pub worker_generation: u64,
}

/// Enforce the required ABI subset; additive compatible capabilities are fine.
///
/// Call this inside every lean-rs session-open boundary, after any replacement,
/// before returning the session to a body command. A previous generation's
/// successful validation cannot stand in for absent current metadata.
///
/// # Errors
/// Refuses absent or incompatible metadata, toolchain or generation identity.
pub(crate) fn validate_loaded(
    expected: &ExpectedContract,
    expected_protocol: u16,
    binding: WorkerBinding<'_>,
    worker_version: &str,
    protocol_version: u16,
    loaded: Option<&LoadedHostRuntime>,
) -> Result<LoadedReceipt, String> {
    let loaded = loaded.ok_or("worker did not report loaded host bindings")?;
    if protocol_version != expected_protocol {
        return Err("parent/child worker protocol mismatch".into());
    }
    if worker_version.trim().is_empty()
        || binding.server_instance_id.trim().is_empty()
        || binding.worker_session_id.trim().is_empty()
        || binding.project_root.is_empty()
        || binding.lean_toolchain.trim().is_empty()
        || loaded.compiled_lean_version.trim().is_empty()
        || !is_digest(binding.expected_header_sha256)
        || loaded.compiled_header_sha256 != binding.expected_header_sha256
        || loaded.runtime_lean_version.as_deref() != Some(binding.expected_runtime_lean_version)
    {
        return Err("worker toolchain or actor identity mismatch".into());
    }
    let epochs = loaded
        .artifact_read_epochs
        .as_ref()
        .ok_or("worker did not report actual read custody")?;
    let mut domains = std::collections::BTreeSet::new();
    if epochs.is_empty()
        || epochs.iter().any(|epoch| {
            let root = std::path::Path::new(&epoch.project_root);
            !root.is_absolute()
                || root.components().any(|component| {
                    matches!(
                        component,
                        std::path::Component::ParentDir | std::path::Component::CurDir
                    )
                })
                || epoch.epoch.is_empty()
                || epoch.epoch.len() > 4096
                || !domains.insert(epoch.project_root.as_str())
        })
        || !domains.contains(binding.project_root)
    {
        return Err("actual read custody does not cover unique canonical project domains".into());
    }
    for (operation, abi) in &expected.required_host_bindings {
        if loaded.checked_host_bindings.get(operation) != Some(abi) {
            return Err(format!("incompatible loaded host binding: {operation}"));
        }
    }
    Ok(LoadedReceipt {
        schema: SCHEMA.into(),
        contract_sha256: expected.digest().map_err(|error| error.to_string())?,
        server_instance_id: binding.server_instance_id.into(),
        project_root: binding.project_root.into(),
        lean_toolchain: binding.lean_toolchain.into(),
        worker_session_id: binding.worker_session_id.into(),
        worker_generation: binding.worker_generation,
        worker_version: worker_version.into(),
        protocol_version,
        loaded: loaded.clone(),
    })
}

fn is_digest(value: &str) -> bool {
    value.len() == 64
        && value
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn contract() -> Result<ExpectedContract, String> {
        ExpectedContract::new(BTreeMap::from([("verify_declaration_batch".into(), "a".repeat(64))]))
    }

    fn loaded() -> Result<LoadedHostRuntime, String> {
        Ok(LoadedHostRuntime {
            artifact_read_epochs: Some(vec![ArtifactReadEpoch {
                project_root: "/proofs".into(),
                epoch: "writer-turn-17".into(),
            }]),
            compiled_lean_version: "4.35.0".into(),
            compiled_header_sha256: "b".repeat(64),
            runtime_lean_version: Some("4.35.0".into()),
            checked_host_bindings: contract()?.required_host_bindings,
        })
    }

    fn receipt(actual: Option<&LoadedHostRuntime>, generation: u64) -> Result<LoadedReceipt, String> {
        validate_loaded(
            &contract()?,
            12,
            WorkerBinding {
                server_instance_id: "broker-original",
                project_root: "/proofs",
                lean_toolchain: "leanprover/lean4:v4.35.0",
                expected_header_sha256: &"b".repeat(64),
                expected_runtime_lean_version: "4.35.0",
                worker_session_id: "actor-original",
                worker_generation: generation,
            },
            "0.9.10",
            12,
            actual,
        )
    }

    #[test]
    fn cold_contract_does_not_claim_a_loaded_worker() -> Result<(), String> {
        let status = serde_json::to_value(contract()?).map_err(|error| error.to_string())?;
        assert!(status.get("loaded").is_none());
        assert!(receipt(None, 1).is_err());
        Ok(())
    }

    #[test]
    fn missing_or_incompatible_binding_prevents_body_execution() -> Result<(), String> {
        let mut actual = loaded()?;
        actual.checked_host_bindings.clear();
        assert!(receipt(Some(&actual), 1).is_err());
        actual
            .checked_host_bindings
            .insert("verify_declaration_batch".into(), "c".repeat(64));
        assert!(receipt(Some(&actual), 1).is_err());
        Ok(())
    }

    #[test]
    fn compatible_additions_and_package_upgrades_preserve_old_evidence() -> Result<(), String> {
        let actual = loaded()?;
        let old = receipt(Some(&actual), 1)?;
        let saved = old.clone();
        let mut newer = actual;
        newer
            .checked_host_bindings
            .insert("new_optional_operation".into(), "d".repeat(64));
        let new = receipt(Some(&newer), 2)?;
        assert_eq!(old, saved);
        assert_eq!(old.contract_sha256, new.contract_sha256);
        assert_ne!(old.worker_generation, new.worker_generation);
        Ok(())
    }

    #[test]
    fn prior_generation_does_not_authorize_replacement_without_metadata() -> Result<(), String> {
        assert!(receipt(Some(&loaded()?), 1).is_ok());
        assert!(receipt(None, 2).is_err());
        Ok(())
    }

    #[test]
    fn wrong_child_toolchain_is_rejected() -> Result<(), String> {
        let mut actual = loaded()?;
        actual.compiled_header_sha256 = "e".repeat(64);
        assert!(receipt(Some(&actual), 1).is_err());
        Ok(())
    }

    #[test]
    fn missing_or_unrelated_read_custody_is_rejected() -> Result<(), String> {
        let mut actual = loaded()?;
        actual.artifact_read_epochs = None;
        assert!(receipt(Some(&actual), 1).is_err());
        actual.artifact_read_epochs = Some(vec![ArtifactReadEpoch {
            project_root: "/other-project".into(),
            epoch: "writer-turn-17".into(),
        }]);
        assert!(receipt(Some(&actual), 1).is_err());
        Ok(())
    }

    #[test]
    fn an_absent_upstream_contract_is_not_a_compatibility_claim() {
        assert!(ExpectedContract::new(BTreeMap::new()).is_err());
    }

    #[test]
    fn digest_matches_the_python_client_fixed_tuple_encoding() -> Result<(), String> {
        assert_eq!(
            contract()?.digest().map_err(|error| error.to_string())?,
            "37c16087fce0de8a2f9795b89e2af9b289f7e224110b6cf30c33200731cf17f6"
        );
        Ok(())
    }

    #[test]
    fn successful_compatibility_cannot_omit_actual_loaded_evidence() -> Result<(), String> {
        assert!(CompatibilityEvidence::new("broker-original".into(), contract()?, vec![]).is_err());
        Ok(())
    }
}

/// Explicit project for the compatibility handshake; it never selects a target proof.
#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub(crate) struct CompatibilityRequest {
    pub project: String,
    /// Explicit versioned discovery never falls back to a loaded handshake.
    #[serde(default)]
    pub mode: CompatibilityMode,
}

/// Pure discovery is opt-in so old deny-unknown-field requests refuse it safely.
#[derive(Clone, Copy, Debug, Default, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub(crate) enum CompatibilityMode {
    /// Existing manual API: open and verify an actual native worker.
    #[default]
    Loaded,
    /// Describe compiled requirements without admitting native work.
    PureV1,
}

/// Compiled requirements and filesystem identity, with no loaded-runtime claim.
#[derive(Debug, Serialize, JsonSchema)]
pub struct PureCompatibilityDescription {
    pub mode: &'static str,
    pub server_instance_id: String,
    pub project_root: PathBuf,
    pub lean_toolchain: String,
    pub worker_protocol_version: u16,
    pub contract_sha256: String,
    pub expected: ExpectedContract,
    pub shared_writer: SharedWriterObservation,
}

/// Worker-free response; intentionally has no `loaded` evidence field.
#[derive(Debug, Serialize, JsonSchema)]
pub struct PureCompatibilityResponse {
    pub status: &'static str,
    pub native_compatibility: PureCompatibilityDescription,
}

impl PureCompatibilityResponse {
    /// Describe only static requirements and the broker's resolved project identity.
    ///
    /// # Errors
    /// Returns unsupported toolchain, SDK contract or helper-identity errors.
    pub fn describe(server_instance_id: String, project_root: PathBuf, lean_toolchain: String) -> Result<Self, String> {
        let expected = ExpectedContract::compiled()?;
        session_expectation(&lean_toolchain, Some(&expected))?;
        let contract_sha256 = expected.digest().map_err(|error| error.to_string())?;
        let writer = lean_rs_writer::contract().map_err(|error| error.to_string())?;
        Ok(Self {
            status: "ok",
            native_compatibility: PureCompatibilityDescription {
                mode: "pure_v1",
                server_instance_id,
                project_root,
                lean_toolchain,
                worker_protocol_version: lean_rs_worker_protocol::protocol::PROTOCOL_VERSION,
                contract_sha256,
                expected,
                shared_writer: writer.into(),
            },
        })
    }
}

/// One handshake response, separate from advisory runtime status.
#[derive(Debug, Serialize, JsonSchema)]
pub struct CompatibilityResponse {
    pub status: String,
    pub native_compatibility: CompatibilityEvidence,
}

/// Requirements for the supported pinned Lean runtime, without probing a process.
///
/// # Errors
/// Returns an error for toolchains outside the supported stable/RC table.
pub(crate) fn session_expectation(
    toolchain: &str,
    contract: Option<&ExpectedContract>,
) -> Result<LeanWorkerHostRuntimeExpectation, String> {
    let label = toolchain.strip_prefix("leanprover/lean4:").unwrap_or(toolchain);
    let version = label.strip_prefix('v').unwrap_or(label);
    let entry = lean_toolchain::SUPPORTED_TOOLCHAINS
        .iter()
        .find(|entry| entry.versions.contains(&version))
        .ok_or_else(|| format!("native compatibility requires a supported pinned Lean toolchain: {toolchain}"))?;
    let compiled = ExpectedContract::compiled()?;
    if contract.is_some_and(|contract| contract != &compiled) {
        return Err("negotiated host contract differs from compiled requirements".into());
    }
    Ok(LeanWorkerHostRuntimeExpectation {
        compiled_header_sha256: Some(entry.header_digest.to_owned()),
        runtime_lean_version: Some(version.to_owned()),
        checked_host_bindings: compiled.required_host_bindings,
    })
}

/// Native check operations, not every optional service the loaded shim offers.
pub(crate) fn contract_from_loaded(actual: &LeanWorkerHostRuntimeMetadata) -> Result<ExpectedContract, String> {
    let expected = ExpectedContract::compiled()?;
    for (operation, abi) in &expected.required_host_bindings {
        if actual.checked_host_bindings.get(operation) != Some(abi) {
            return Err(format!(
                "loaded host differs from compiled native operation: {operation}"
            ));
        }
    }
    Ok(expected)
}

/// Bind actual child facts to the actor/generation that returned this call.
pub(crate) fn evidence(
    contract: ExpectedContract,
    server_instance_id: String,
    project_root: &str,
    toolchain: &str,
    session_id: &str,
    generation: u64,
    runtime: &LeanWorkerRuntimeMetadata,
    actual: &LeanWorkerHostRuntimeMetadata,
) -> Result<CompatibilityEvidence, String> {
    let expectation = session_expectation(toolchain, Some(&contract))?;
    expectation.validate(actual)?;
    let loaded = LoadedHostRuntime {
        artifact_read_epochs: actual.artifact_read_epochs.as_ref().map(|epochs| {
            epochs
                .iter()
                .map(|epoch| ArtifactReadEpoch {
                    project_root: epoch.project_root.clone(),
                    epoch: epoch.epoch.clone(),
                })
                .collect()
        }),
        compiled_lean_version: actual.compiled_lean_version.clone(),
        compiled_header_sha256: actual.compiled_header_sha256.clone(),
        runtime_lean_version: actual.runtime_lean_version.clone(),
        checked_host_bindings: actual.checked_host_bindings.clone(),
    };
    let receipt = validate_loaded(
        &contract,
        lean_rs_worker_protocol::protocol::PROTOCOL_VERSION,
        WorkerBinding {
            server_instance_id: &server_instance_id,
            project_root,
            lean_toolchain: toolchain,
            expected_header_sha256: expectation.compiled_header_sha256.as_deref().unwrap_or(""),
            expected_runtime_lean_version: expectation.runtime_lean_version.as_deref().unwrap_or(""),
            worker_session_id: session_id,
            worker_generation: generation,
        },
        &runtime.worker_version,
        runtime.protocol_version,
        Some(&loaded),
    )?;
    CompatibilityEvidence::new(server_instance_id, contract, vec![receipt])
}

#[cfg(test)]
mod pure_tests {
    use super::*;

    #[test]
    fn pure_mode_is_explicit_and_rejected_by_old_request_before_dispatch() -> Result<(), Box<dyn std::error::Error>> {
        #[derive(Deserialize)]
        #[serde(deny_unknown_fields)]
        struct OldRequest {
            project: String,
        }
        let input = serde_json::json!({"project":"/proofs","mode":"pure_v1"});
        let request: CompatibilityRequest = serde_json::from_value(input.clone())?;
        assert!(matches!(request.mode, CompatibilityMode::PureV1));
        assert!(serde_json::from_value::<OldRequest>(input).is_err());
        let old: OldRequest = serde_json::from_value(serde_json::json!({"project":"/proofs"}))?;
        assert_eq!(old.project, "/proofs");
        let default: CompatibilityRequest = serde_json::from_value(serde_json::json!({"project":"/proofs"}))?;
        assert!(matches!(default.mode, CompatibilityMode::Loaded));
        assert!(
            serde_json::from_value::<CompatibilityRequest>(serde_json::json!({"project":"/proofs","mode":"future"}))
                .is_err()
        );
        Ok(())
    }

    #[test]
    fn first_cold_expectation_requires_all_compiled_bindings_and_pinned_runtime() -> Result<(), String> {
        let expected = session_expectation("leanprover/lean4:v4.35.0", None)?;
        assert_eq!(
            expected.checked_host_bindings,
            lean_toolchain::host_shim_abi::expected_checked_bindings()
        );
        assert_eq!(expected.checked_host_bindings.len(), 3);
        let mut actual = LeanWorkerHostRuntimeMetadata {
            effective_import_roots: None,
            artifact_read_epochs: None,
            compiled_lean_version: "4.35.0".into(),
            compiled_header_sha256: expected.compiled_header_sha256.clone().ok_or("header missing")?,
            runtime_lean_version: expected.runtime_lean_version.clone(),
            checked_host_bindings: expected.checked_host_bindings.clone(),
        };
        expected.validate(&actual)?;
        actual
            .checked_host_bindings
            .insert("verify_declaration_batch".into(), "wrong-abi".into());
        assert!(expected.validate(&actual).is_err());
        actual.checked_host_bindings = expected.checked_host_bindings.clone();
        actual.checked_host_bindings.remove("runtime_version");
        assert!(expected.validate(&actual).is_err());
        actual.checked_host_bindings = expected.checked_host_bindings.clone();
        actual.compiled_header_sha256 = "wrong-header".into();
        assert!(expected.validate(&actual).is_err());
        actual.compiled_header_sha256 = expected.compiled_header_sha256.clone().ok_or("header missing")?;
        actual.runtime_lean_version = Some("4.34.0".into());
        assert!(expected.validate(&actual).is_err());
        assert!(session_expectation("v0.0.0", None).is_err());
        Ok(())
    }

    #[test]
    fn actual_metadata_cannot_teach_the_compiled_contract() -> Result<(), String> {
        let expectation = session_expectation("v4.35.0", None)?;
        let mut actual = LeanWorkerHostRuntimeMetadata {
            effective_import_roots: None,
            artifact_read_epochs: None,
            compiled_lean_version: "4.35.0".into(),
            compiled_header_sha256: expectation.compiled_header_sha256.ok_or("header missing")?,
            runtime_lean_version: expectation.runtime_lean_version,
            checked_host_bindings: expectation.checked_host_bindings,
        };
        let expected = ExpectedContract::compiled()?;
        assert_eq!(contract_from_loaded(&actual)?, expected);
        actual
            .checked_host_bindings
            .insert("verify_declaration_batch".into(), "wrong-abi".into());
        assert!(contract_from_loaded(&actual).is_err());
        let mut forged = expected;
        forged.required_host_bindings = actual.checked_host_bindings;
        assert!(session_expectation("v4.35.0", Some(&forged)).is_err());
        Ok(())
    }
}
